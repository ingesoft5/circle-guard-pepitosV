#!/usr/bin/env bash
# Starts, stops and lists the CircleGuard hosts, and keeps their current IPs in one file.
# Usage: hosts.sh <status|refresh|start|stop> [ci|envs|all]
#        hosts.sh allow <public-ip>   grants a team member the documented admin ports
# Public IPs of the environments change on every start: read them from hosts.env (not versioned).
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
source "${SCRIPT_DIR}/../../bootstrap/lib/common.sh"

readonly HOSTS_FILE="${SCRIPT_DIR}/hosts.env"
readonly ALL_HOSTS=(ci dev stage prod)
export AWS_DEFAULT_REGION="${AWS_REGION:-us-east-1}"
export AWS_PAGER=""

usage() {
  die "Usage: $(basename "$0") <status|refresh|start|stop> [ci|envs|all] | allow <public-ip>"
}

hosts_of() {
  case "$1" in
    ci) echo ci ;;
    envs) echo dev stage prod ;;
    all) echo "${ALL_HOSTS[*]}" ;;
    *) usage ;;
  esac
}

describe_host() {
  aws ec2 describe-instances \
    --filters "Name=tag:Name,Values=circleguard-$1" "Name=tag:Project,Values=CircleGuard" \
      "Name=instance-state-name,Values=pending,running,stopping,stopped" \
    --query 'Reservations[0].Instances[0].[InstanceId,State.Name,PrivateIpAddress,PublicIpAddress]' \
    --output text
}

instance_ids_of() {
  local host id
  for host in "$@"; do
    read -r id _ < <(describe_host "${host}")
    [[ "${id}" == i-* ]] || die "Host not found: circleguard-${host}"
    printf '%s\n' "${id}"
  done
}

refresh() {
  local host upper id state private_ip public_ip tmp
  tmp="$(mktemp)"
  printf '# Generated by hosts.sh on %s. Do not edit.\n' "$(date -u +%FT%TZ)" >"${tmp}"
  for host in "${ALL_HOSTS[@]}"; do
    read -r id state private_ip public_ip < <(describe_host "${host}")
    upper="${host^^}"
    [[ "${public_ip}" == "None" ]] && public_ip=""
    [[ "${private_ip}" == "None" ]] && private_ip=""
    printf '%s_PUBLIC_IP=%s\n%s_PRIVATE_IP=%s\n' "${upper}" "${public_ip}" "${upper}" "${private_ip}" >>"${tmp}"
    printf '%-6s %-20s %-8s private=%-15s public=%s\n' \
      "${host}" "${id}" "${state}" "${private_ip:--}" "${public_ip:--}"
  done
  mv "${tmp}" "${HOSTS_FILE}"
  chmod 600 "${HOSTS_FILE}"
  info "IPs saved in ${HOSTS_FILE}"
}

add_rule() {
  local sg_name="$1" from_port="$2" to_port="$3" cidr="$4" sg_id output
  sg_id="$(aws ec2 describe-security-groups --filters "Name=group-name,Values=${sg_name}" \
    --query 'SecurityGroups[0].GroupId' --output text)"
  [[ "${sg_id}" == sg-* ]] || die "Security Group not found: ${sg_name}"
  if output="$(aws ec2 authorize-security-group-ingress --group-id "${sg_id}" \
    --ip-permissions "IpProtocol=tcp,FromPort=${from_port},ToPort=${to_port},IpRanges=[{CidrIp=${cidr}}]" 2>&1)"; then
    info "${sg_name}: rule added ${from_port}-${to_port}/tcp from ${cidr}"
  elif grep -q "InvalidPermission.Duplicate" <<<"${output}"; then
    info "${sg_name}: rule already exists ${from_port}-${to_port}/tcp from ${cidr}"
  else
    die "Could not add the rule to ${sg_name}: ${output}"
  fi
}

allow_admin_ip() {
  local ip="${1:-}" cidr port env_name
  [[ "${ip}" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || usage
  cidr="${ip}/32"
  for port in 22 8080 9000 8081 5000; do
    add_rule circleguard-ci-sg "${port}" "${port}" "${cidr}"
  done
  for env_name in dev stage prod; do
    add_rule "circleguard-${env_name}-sg" 22 22 "${cidr}"
    add_rule "circleguard-${env_name}-sg" 8180 8180 "${cidr}"
    add_rule "circleguard-${env_name}-sg" 8082 8088 "${cidr}"
  done
}

main() {
  require_cmd aws
  local action="${1:-}" target="${2:-all}" ids
  case "${action}" in
    status | refresh)
      refresh
      ;;
    allow)
      allow_admin_ip "${2:-}"
      ;;
    start)
      # shellcheck disable=SC2046
      mapfile -t ids < <(instance_ids_of $(hosts_of "${target}"))
      aws ec2 start-instances --instance-ids "${ids[@]}" >/dev/null
      aws ec2 wait instance-running --instance-ids "${ids[@]}"
      refresh
      ;;
    stop)
      # shellcheck disable=SC2046
      mapfile -t ids < <(instance_ids_of $(hosts_of "${target}"))
      aws ec2 stop-instances --instance-ids "${ids[@]}" >/dev/null
      aws ec2 wait instance-stopped --instance-ids "${ids[@]}"
      refresh
      ;;
    *)
      usage
      ;;
  esac
}

main "$@"
