/**
 * Actualiza CHANGELOG.md mediante un pull request hacia dev (HU-22).
 *
 *   openChangelogPr(version: '1.3.0', changelog: releaseNotes.changelog())
 *
 * main y dev están protegidas (PR obligatorio), así que el pipeline no hace push
 * directo: escribe CHANGELOG.md sobre origin/dev en la rama chore/changelog, la
 * publica y abre (o actualiza) el PR "chore(release): update changelog for vX.Y.Z".
 * El archivo se regenera completo en cada release, así que un PR anterior sin
 * fusionar no pierde versiones: la rama se reemplaza con el contenido nuevo.
 * Si dev ya tiene ese CHANGELOG.md, no hace nada.
 */
def call(Map config = [:]) {
    String version = (config.version ?: '').toString().trim()
    if (!semver.isVersion(version)) {
        error("openChangelogPr: '${version}' no es una versión MAJOR.MINOR.PATCH")
    }
    String changelog = config.changelog
    if (!changelog) {
        error('openChangelogPr: falta "changelog" (use releaseNotes.changelog())')
    }
    String base = config.base ?: 'dev'
    String branch = config.branch ?: 'chore/changelog'
    String repo = config.repository ?: releaseNotes.repository()
    String api = config.apiUrl ?: (env.GITHUB_API_URL ?: 'https://api.github.com')
    String credentialsId = config.credentialsId ?: 'github-pat'
    String title = "chore(release): update changelog for v${version}"
    String worktree = '.changelog-worktree'

    withEnv([
        "BASE_BRANCH=${base}", "PR_BRANCH=${branch}", "WT=${worktree}", "COMMIT_TITLE=${title}",
        "GH_REPO_API=${api}/repos/${repo}", "GH_OWNER=${repo.tokenize('/')[0]}"
    ]) {
        withCredentials([gitUsernamePassword(credentialsId: credentialsId)]) {
            // Explicit refspec: the main build clones only main, so a plain fetch leaves
            // origin/<base> undefined and the worktree below fails.
            sh 'git fetch --quiet origin "+refs/heads/$BASE_BRANCH:refs/remotes/origin/$BASE_BRANCH"'
        }
        // Un worktree aparte para no tocar el checkout del build (el commit del release).
        sh 'rm -rf "$WT" && git worktree prune && git worktree add --quiet -B "$PR_BRANCH" "$WT" "origin/$BASE_BRANCH"'
        try {
            writeFile file: "${worktree}/CHANGELOG.md", text: changelog
            int unchanged = sh(script: 'cd "$WT" && git add CHANGELOG.md && git diff --cached --quiet', returnStatus: true)
            if (unchanged == 0) {
                echo "openChangelogPr: CHANGELOG.md de ${base} ya incluye v${version}; no se abre PR"
            } else {
                sh '''
                    cd "$WT"
                    git -c user.name="CircleGuard CI" -c user.email="ci@circleguard.local" commit --quiet \
                      -m "$COMMIT_TITLE" -m "Generated by the Jenkins pipeline from Conventional Commits (HU-22)."
                '''
                withCredentials([gitUsernamePassword(credentialsId: credentialsId)]) {
                    sh 'cd "$WT" && git push --force --quiet origin "HEAD:refs/heads/$PR_BRANCH"'
                }
                ensurePullRequest(credentialsId, title, version, base, branch)
            }
        } finally {
            sh 'git worktree remove --force "$WT" >/dev/null 2>&1 || rm -rf "$WT"; git worktree prune; git branch -D "$PR_BRANCH" >/dev/null 2>&1 || true'
        }
    }
}

def ensurePullRequest(String credentialsId, String title, String version, String base, String branch) {
    writeFile file: '.changelog-pr.json', text: prPayload(title, version, base, branch)
    withCredentials([usernamePassword(credentialsId: credentialsId,
            usernameVariable: 'GH_USER', passwordVariable: 'GH_TOKEN')]) {
        try {
            String open = sh(script: '''
                curl -sS -f -H "Authorization: Bearer $GH_TOKEN" -H "Accept: application/vnd.github+json" \
                  "$GH_REPO_API/pulls?state=open&base=$BASE_BRANCH&head=$GH_OWNER:$PR_BRANCH"
            ''', returnStdout: true)
            String number = firstPrNumber(open)

            String method = number ? 'PATCH' : 'POST'
            String path = number ? "pulls/${number}" : 'pulls'
            String status
            withEnv(["GH_METHOD=${method}", "GH_PATH=${path}"]) {
                status = sh(script: '''
                    curl -sS -o .changelog-pr-response.json -w '%{http_code}' -X "$GH_METHOD" \
                      -H "Authorization: Bearer $GH_TOKEN" -H "Accept: application/vnd.github+json" \
                      -H "Content-Type: application/json" --data @.changelog-pr.json "$GH_REPO_API/$GH_PATH"
                ''', returnStdout: true).trim()
            }
            String response = readFile('.changelog-pr-response.json')
            if (!(status ==~ /2\d\d/)) {
                error("openChangelogPr: GitHub respondió HTTP ${status}: ${response.take(300)}")
            }
            echo "openChangelogPr: PR ${number ? 'actualizado' : 'abierto'} ${publishGithubRelease.jsonField(response, 'html_url')}"
        } finally {
            sh 'rm -f .changelog-pr.json .changelog-pr-response.json'
        }
    }
}

@NonCPS
String prPayload(String title, String version, String base, String branch) {
    String body = "Actualiza `CHANGELOG.md` con la versión `v${version}`.\n\n" +
            'Generado automáticamente por el pipeline de Jenkins a partir de los Conventional Commits (HU-22). ' +
            'Solo modifica `CHANGELOG.md`; al fusionarlo llega a `main` con la siguiente promoción.\n\n' +
            '**Type of change:** chore\n\nRefs: CGR-45'
    return groovy.json.JsonOutput.toJson([title: title, head: branch, base: base, body: body])
}

@NonCPS
String firstPrNumber(String json) {
    def list = new groovy.json.JsonSlurperClassic().parseText(json ?: '[]')
    return list ? list[0].number.toString() : null
}
