package com.circleguard.promotion.service;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import com.circleguard.promotion.model.graph.CircleNode;
import com.circleguard.promotion.repository.graph.CircleNodeRepository;
import com.circleguard.promotion.repository.graph.UserNodeRepository;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;

class AutoCircleServiceTest {

    private UserNodeRepository userRepository;
    private CircleNodeRepository circleRepository;
    private CircleService circleService;
    private AutoCircleService service;

    @BeforeEach
    void setUp() {
        userRepository = mock(UserNodeRepository.class);
        circleRepository = mock(CircleNodeRepository.class);
        circleService = mock(CircleService.class);
        service = new AutoCircleService(userRepository, circleRepository, circleService);
    }

    @Test
    void anHourTogetherCreatesAnAutomaticCircleForBoth() {
        when(userRepository.getCumulativeEncounterDuration("a", "b")).thenReturn(3600L);
        when(circleRepository.findCommonCircles("a", "b")).thenReturn(List.of(CircleNode.builder().isAutoGenerated(false).build()));

        service.evaluateEncounter("a", "b");

        ArgumentCaptor<CircleNode> saved = ArgumentCaptor.forClass(CircleNode.class);
        verify(circleRepository).save(saved.capture());
        String code = saved.getValue().getInviteCode();
        org.assertj.core.api.Assertions.assertThat(code).startsWith("AUTO-");
        org.assertj.core.api.Assertions.assertThat(saved.getValue().getIsAutoGenerated()).isTrue();
        verify(circleService).joinCircle("a", code);
        verify(circleService).joinCircle("b", code);
    }

    @Test
    void usersAlreadyInAnAutomaticCircleAreLeftAlone() {
        when(userRepository.getCumulativeEncounterDuration("a", "b")).thenReturn(7200L);
        when(circleRepository.findCommonCircles("a", "b")).thenReturn(List.of(CircleNode.builder().isAutoGenerated(true).build()));

        service.evaluateEncounter("a", "b");

        verify(circleRepository, never()).save(any());
    }

    @Test
    void shortOrUnknownEncountersDoNotCreateCircles() {
        when(userRepository.getCumulativeEncounterDuration("a", "b")).thenReturn(3599L);
        service.evaluateEncounter("a", "b");
        when(userRepository.getCumulativeEncounterDuration("a", "b")).thenReturn(null);
        service.evaluateEncounter("a", "b");

        verify(circleRepository, never()).save(any());
        verify(circleService, never()).joinCircle(anyString(), anyString());
    }

    @Test
    void invalidPairsAreIgnored() {
        service.evaluateEncounter(null, "b");
        service.evaluateEncounter("a", null);
        service.evaluateEncounter("a", "a");

        verifyNoInteractions(userRepository, circleRepository, circleService);
    }
}
